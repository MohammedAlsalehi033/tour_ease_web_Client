// app/layout.tsx
import 'reflect-metadata';
import type { Metadata } from "next";
import "./globals.css";
import { ThemeProvider } from "next-themes";
import MySideBar from "./(view)/components/MySideBar";
import Providers from './(view)/components/Providers';
import { getServerSession } from 'next-auth';
import { authOptions } from './api/auth/[...nextauth]/route';
import { Suspense } from 'react';
import SidebarSkeleton from './(view)/components/SidebarSkeleton';
import { container } from 'tsyringe';
import { BookingController } from './(controller)/rideSharing/bookingController';
import NotificationIcon from './(view)/components/notificationIcon';
import { ActiveRideProvider } from '@/app/components/ActiveRideProvider';

export const metadata: Metadata = {
  title: "TourEase",
  description: "Generated by create next app",
};

async function getActiveRideStatus() {
 const bookingController = container.resolve(BookingController);
  try {
    const session = await getServerSession(authOptions);
    if (!session?.user?.id) {
      return { hasActiveRide: false };
    }
    const bookings = await bookingController.getBookingsForTraveler(session.user.id);
    const bookingForDriver = await bookingController.getBookingsForDriver(session.user.id);
   
    console.log(bookingForDriver)
    const hasActiveRide = bookings.data.some(booking => booking.status === 'pending') || bookingForDriver.data.some(booking => booking.status === 'pending');
    console.log(hasActiveRide)
    return { hasActiveRide };
  } catch (error) {
    console.error("Error fetching active ride status:", error);
    return { hasActiveRide: false };
  }
}

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const { hasActiveRide } = await getActiveRideStatus();


  return (
    <html lang="en">
      <head>
        <link rel="stylesheet" href="https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.4.0/css/all.min.css" />
      </head>
      <body className="font-lina">
        <ThemeProvider attribute="class">
          <Providers>
            <ActiveRideProvider>
              <Suspense fallback={<SidebarSkeleton />}>
                <MySideBar hasActiveRide={hasActiveRide} />
              </Suspense>
              <NotificationIcon />
              <div className="min-h-screen bg-light-background dark:bg-dark-background transition-colors duration-300 xl:pl-72 p-5 md:p-5">
                {children}
              </div>
            </ActiveRideProvider>
          </Providers>
        </ThemeProvider>
      </body>
    </html>
  );
}